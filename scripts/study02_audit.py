"""Study 02 groundwork: re-analysis of the Study 01 artifacts. Needs no model and no GPU.

    python scripts/study02_audit.py        # writes docs/study02/audit_tables.md

It answers three questions that shape the Study 02 design:
  1. How uncertain is "success on unseen templates" when the *template* (not the task) is the
     unit that generalisation is claimed over?
  2. What did training actually cover (gold tools, distinct dependency graphs)?
  3. Given the variance observed in Study 01, how small a difference between two training
     arms can a design with F held-out families, S seeds and m tasks per family detect?
"""

from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ccl.tasks import Task, graph_signature  # noqa: E402

RUNS = ROOT / "results/runs"
DATA = ROOT / "data/v1/tasks"
OUT = ROOT / "docs/study02/audit_tables.md"
ARMS = ["B", "C", "Dmix"]  # the three-seed arms whose comparison Study 01 was built around


def load_runs() -> dict[str, dict[int, list[dict]]]:
    out: dict[str, dict[int, list[dict]]] = defaultdict(dict)
    for d in sorted(RUNS.iterdir()):
        m = re.fullmatch(r"(.+)_s(\d+)", d.name)
        cfg, seed = (m.group(1), int(m.group(2))) if m else (d.name, 0)
        out[cfg][seed] = [json.loads(line) for line in open(d / "metrics.jsonl")]
    return out


def cells(rows_by_seed: dict[int, list[dict]], split: str):
    """seeds x templates matrices: mean success and number of tasks."""
    templates = sorted({r["template"] for r in rows_by_seed[min(rows_by_seed)] if r["split"] == split})
    mean = np.zeros((len(rows_by_seed), len(templates)))
    n = np.zeros_like(mean)
    for si, seed in enumerate(sorted(rows_by_seed)):
        by = defaultdict(list)
        for r in rows_by_seed[seed]:
            if r["split"] == split:
                by[r["template"]].append(r["success"])
        for ti, t in enumerate(templates):
            mean[si, ti], n[si, ti] = np.mean(by[t]), len(by[t])
    return templates, mean, n


def cluster_ci(mean: np.ndarray, n_boot: int = 10_000, seed: int = 0) -> tuple[float, float, float]:
    """Resample seeds and templates (both with replacement); every template weighs the same."""
    rng = np.random.default_rng(seed)
    s, f = mean.shape
    boots = [mean[np.ix_(rng.integers(0, s, s), rng.integers(0, f, f))].mean() for _ in range(n_boot)]
    return float(mean.mean()), float(np.quantile(boots, 0.025)), float(np.quantile(boots, 0.975))


def variance_components(runs, split: str) -> dict:
    """Method-of-moments components of per-task success on the probability scale.

    within       task-to-task variance inside a (seed, template) cell
    seed_family  how much a template's success moves from one training seed to the next
    seed         seed effect on the split mean that is left after seed_family is averaged out
    arm_family   how much the difference between two arms varies from template to template
    """
    comp = {}
    for cfg in ARMS:
        _, mean, n = cells(runs[cfg], split)
        s, f = mean.shape
        within = float(np.mean(mean * (1 - mean)))
        sf = float(np.mean(mean.var(axis=0, ddof=1)) - np.mean(mean * (1 - mean) / np.maximum(n - 1, 1)))
        seed = float(mean.mean(axis=1).var(ddof=1) - max(sf, 0) / f - within / n.sum(axis=1).mean())
        comp[cfg] = {"within": within, "seed_family": sf, "seed": seed, "family_sd": float(mean.mean(0).std(ddof=1))}
    pairs = {}
    for a, b in [("B", "C"), ("C", "Dmix"), ("B", "Dmix")]:
        _, ma, na = cells(runs[a], split)
        _, mb, _ = cells(runs[b], split)
        diff = mb.mean(0) - ma.mean(0)
        s, m = ma.shape[0], na.mean()
        noise = sum(max(comp[x]["seed_family"], 0) / s + comp[x]["within"] / (s * m) for x in (a, b))
        pairs[f"{b} - {a}"] = {"mean_diff": float(diff.mean()), "raw_sd": float(diff.std(ddof=1)),
                               "arm_family": float(diff.var(ddof=1) - noise)}
    return {"arms": comp, "pairs": pairs}


def se_diff(F: int, S: int, m: int, arm_family: float, seed_family: float, within: float, seed: float) -> float:
    """Standard error of the difference in mean success between two arms evaluated on the same
    F families x m tasks, each arm trained with S independent seeds."""
    return float(np.sqrt(2 * seed / S + arm_family / F + 2 * seed_family / (S * F) + 2 * within / (S * F * m)))


def main():
    runs = load_runs()
    summary = json.loads((ROOT / "results/summary.json").read_text())
    md = ["# Study 01 re-analysis for the Study 02 design",
          "",
          "*Generated by `scripts/study02_audit.py` from `results/runs/*/metrics.jsonl` and `data/v1/tasks`. "
          "Post-hoc: every analysis here was chosen after the Study 01 results were known.*", ""]

    # ---- 1. template-level view of the unseen-template split
    md += ["## 1. `eval_ood` by template (success %, seeds pooled, 15 tasks per template)", ""]
    cfgs = ["A_fewshot", "B", "C", "Dmix", "Dseq", "teacher"]
    templates, _, _ = cells(runs["B"], "eval_ood")
    train = [json.loads(line) for line in open(DATA / "train_pool.jsonl")]
    ood = [json.loads(line) for line in open(DATA / "eval_ood.jsonl")]
    gold_train = Counter(g["tool"] for t in train for g in t["gold"])
    novel_tools = defaultdict(set)
    for t in ood:
        novel_tools[t["template"]] |= {g["tool"] for g in t["gold"]} - set(gold_train)
    md += ["| template | " + " | ".join(cfgs) + " | gold tools never gold in training |",
           "|---|" + "---|" * (len(cfgs) + 1)]
    table = {}
    for c in cfgs:
        tpls, mean, _ = cells(runs[c], "eval_ood")
        table[c] = dict(zip(tpls, mean.mean(0)))
    for t in templates:
        md.append(f"| {t} | " + " | ".join(f"{100 * table[c][t]:.0f}" for c in cfgs)
                  + f" | {', '.join(sorted(novel_tools[t])) or '-'} |")
    md += ["", "## 2. Uncertainty when the template is the unit of generalisation", "",
           "Study 01 resampled seeds and tasks. A claim about *unseen templates* needs templates resampled too. "
           "Both intervals are 95%.", "",
           "| config | eval_ood mean | reported CI (seeds, tasks) | CI resampling seeds and the 16 templates |",
           "|---|---|---|---|"]
    for c in ["B", "C", "Dmix", "Dseq", "teacher"]:
        rep = summary["configs"][c]["eval_ood"]["success"]
        mean, lo, hi = cluster_ci(cells(runs[c], "eval_ood")[1])
        md.append(f"| {c} | {100 * mean:.1f} | [{100 * rep['lo']:.1f}, {100 * rep['hi']:.1f}] | "
                  f"[{100 * lo:.1f}, {100 * hi:.1f}] |")

    # ---- 2. coverage
    sigs = Counter(graph_signature(Task.from_dict(t)) for t in train)
    ood_sigs = {graph_signature(Task.from_dict(t)) for t in ood}
    catalogue_tools = {s["impl"] or s["name"] for t in train for s in t["catalog"]}
    eval_id_n = Counter(t["template"] for t in map(json.loads, open(DATA / "eval_id.jsonl")))
    md += ["", "## 3. What training covered", "",
           f"- Training pool: {len(train)} tasks from {len({t['template'] for t in train})} templates, "
           f"**{len(sigs)} distinct gold-graph signatures**.",
           f"- `eval_ood`: {len(ood_sigs)} signatures, {len(ood_sigs - set(sigs))} of them absent from training.",
           f"- Tools that are gold in at least one training task: {len(gold_train)} of "
           f"{len(catalogue_tools)} that appear in training catalogues. Never gold, only distractor or fallback: "
           f"{', '.join(sorted(catalogue_tools - set(gold_train)))}.",
           f"- `eval_ood` templates that need a tool never used as gold in training: "
           f"{sum(bool(v) for v in novel_tools.values())} of {len(templates)}.",
           f"- `eval_id` tasks per template range from {min(eval_id_n.values())} to {max(eval_id_n.values())} "
           f"(the verbatim-overlap filter removed most instances of low-entropy templates)."]

    # ---- 3. variance components and detectable effects
    vc = variance_components(runs, "eval_ood")
    md += ["", "## 4. Variance components on `eval_ood` (probability scale)", "",
           "| arm | task-level variance within a cell | seed x template sd | residual seed sd | sd across templates |",
           "|---|---|---|---|---|"]
    for c, v in vc["arms"].items():
        md.append(f"| {c} | {v['within']:.3f} | {np.sqrt(max(v['seed_family'], 0)):.3f} | "
                  f"{np.sqrt(max(v['seed'], 0)):.3f} | {v['family_sd']:.3f} |")
    md += ["", "| pair | mean difference | sd of the per-template difference | arm x template sd after removing "
               "seed and task noise |", "|---|---|---|---|"]
    for p, v in vc["pairs"].items():
        md.append(f"| {p} | {100 * v['mean_diff']:+.1f} | {v['raw_sd']:.3f} | {np.sqrt(max(v['arm_family'], 0)):.3f} |")

    seed_family = float(np.mean([max(v["seed_family"], 0) for v in vc["arms"].values()]))
    within = float(np.mean([v["within"] for v in vc["arms"].values()]))
    af = sorted(max(v["arm_family"], 0) for v in vc["pairs"].values())
    scenarios = {"arm x family sd as between Dmix and a single source": af[0],
                 "arm x family sd as between teacher and oracle data": af[-1]}
    designs = [("Study 01 eval_ood", 16, 3, 15), ("", 60, 5, 5), ("", 150, 5, 4), ("proposed", 300, 5, 4),
               ("", 300, 8, 4), ("", 600, 5, 2)]
    md += ["", "## 5. Smallest detectable difference between two arms", "",
           "`se^2 = 2*seed/S + arm_family/F + 2*seed_family/(S*F) + 2*within/(S*F*m)` for F held-out families, "
           "S seeds per arm, m tasks per family, both arms scored on the same tasks. Detectable difference = "
           "2.80 x se (two-sided 5%, 80% power). The last column is the non-inferiority margin that a truly "
           "equal pair passes with 80% power (2.49 x se, one-sided 5%). "
           f"Inputs from section 4: seed x family variance {seed_family:.4f}, within-cell variance {within:.3f}. "
           "The residual seed sd is not distinguishable from zero on `eval_ood`, so two assumed values are shown.", ""]
    for name, arm_family in scenarios.items():
        md += [f"**{name} ({np.sqrt(arm_family):.2f})**", "",
               "| design | F | S | m | tasks | detectable diff, seed sd 0.02 | detectable diff, seed sd 0.05 | "
               "non-inferiority margin, seed sd 0.02 |", "|---|---|---|---|---|---|---|---|"]
        for label, F, S, m in designs:
            se2, se5 = (se_diff(F, S, m, arm_family, seed_family, within, sd ** 2) for sd in (0.02, 0.05))
            md.append(f"| {label} | {F} | {S} | {m} | {F * m} | {280 * se2:.1f} pts | {280 * se5:.1f} pts | "
                      f"{249 * se2:.1f} pts |")
        md.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
