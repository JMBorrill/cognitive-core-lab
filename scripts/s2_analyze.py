def cube(names: list[str], split: str, key: str = "success", mask=None):
    """(replicates, families, tasks) array of `key` for runs `names` on a fixed split, aligned on family and task.

    `mask(name, family)` may return False to blank a family for a run (restricted endpoints)."""
    per = []
    for n in names:
        fam = defaultdict(dict)
        for r in load("e1", n):
            if r["split"] == split:
                fam[r["template"]][r["task_id"]] = float(r[key])
        per.append(fam)
    fams = sorted(per[0])
    assert all(sorted(f) == fams for f in per), f"runs disagree on the families of {split}"
    m = min(len(per[0][f]) for f in fams)
    y = np.array([[[fam[f][t] for t in sorted(fam[f])[:m]] for f in fams] for fam in per])
    if mask:
        for i, n in enumerate(names):
            for j, f in enumerate(fams):
                if not mask(n, f):
                    y[i, j, :] = np.nan
    return y, fams


def boot(y_by_arm: list[np.ndarray], seed: int = 0) -> np.ndarray:
    """cluster_bootstrap that tolerates blanked families (restricted endpoints)."""
    y = np.stack(y_by_arm)
    if not np.isnan(y).any():
        return cluster_bootstrap(y, N_BOOT, seed)
    a, r, f, m = y.shape
    rng = np.random.default_rng(seed)
    fam = np.arange(f)[:, None]
    out = np.empty((N_BOOT, a))
    for b in range(N_BOOT):
        ri, fi, ti = rng.integers(0, r, r), rng.integers(0, f, f), rng.integers(0, m, (f, m))
        out[b] = np.nanmean(y[:, ri][:, :, fi][:, :, fam, ti], axis=(1, 2, 3))
    return out


def verdict(diff: dict) -> str:
    """H1 as pre-registered: supported if >= 10 points and the interval excludes zero; refuted if the
    interval lies entirely below +10 points; otherwise inconclusive."""
    if diff["mean"] >= 0.10 and diff["lo"] > 0:
        return "supported"
    if diff["hi"] < 0.10:
        return "refuted"
    return "inconclusive"


def e1() -> None:
    out = OUT / "e1"
    out.mkdir(parents=True, exist_ok=True)
    sets = json.loads((out / "training_sets.json").read_text())
    sealed = {f["id"]: f for f in s2.read_gz(s2.V2 / "sealed/families.jsonl.gz")}
    sealed.update({f["id"]: f for f in s2.read_gz(s2.V2 / "dev/families.jsonl.gz")})
    S: dict = {"students": {}, "baselines": {}, "coverage": {}}
    md = ["# Study 02, Experiment 1: results (generated by scripts/s2_analyze.py e1)", "",
          "Intervals are 95%, from a hierarchical bootstrap with 10,000 resamples of replicates, then families, "
          "then tasks within families; contrasts are paired on replicate, family and task.", ""]

    def names(tag, d, reps):
        return [f"e1_{tag}_D{d}_r{r}" for r in reps]

    def covered(kind):
        def ok(run, fam):
            r, d = run.split("_")[-1], run.split("_")[-2]
            have = set(sets[f"{r}_{d}"][kind])
            return set(sealed[fam][kind]) <= have
        return ok

    for tag, levels, reps in (("s05", LEVELS, range(5)), ("s15", [25, 1600], range(3))):
        have = [d for d in levels if all((RUNS / "e1" / n / "DONE").exists() for n in names(tag, d, reps))]
        if len(have) < 2:
            continue
        R: dict = {"levels": have, "replicates": len(list(reps)), "splits": {}}
        label = {"s05": "Qwen2.5-0.5B-Instruct", "s15": "Qwen2.5-1.5B-Instruct"}[tag]
        md += [f"## {label} ({len(list(reps))} replicates per level)", ""]

        # ---- primary endpoint
        ys = [cube(names(tag, d, reps), "v2/test_comp")[0] for d in have]
        bs = boot(ys)
        means = [float(y.mean()) for y in ys]
        prim = {str(d): {**interval(bs[:, i], means[i]), "replicate_means": [float(x) for x in ys[i].mean(axis=(1, 2))]}
                for i, d in enumerate(have)}
        lo, hi = have.index(25), have.index(1600)
        diff = interval(bs[:, hi] - bs[:, lo], means[hi] - means[lo])
        x = np.log2(np.array(have, dtype=float))
        slope = lambda v: float(np.polyfit(x, v, 1)[0])  # noqa: E731
        sl = interval([slope(b) for b in bs], slope(np.array(means))) if len(have) > 2 else None
        R["primary"] = {"test_comp": prim, "D1600_minus_D25": diff, "H1": verdict(diff), "slope_per_doubling": sl,
                        "ceiling_at_D1600": prim["1600"]["mean"], "ceiling_at_least_40": prim["1600"]["mean"] >= 0.40}
        md += ["### Primary endpoint: success on `test_comp` (600 families x 2 tasks)", "",
               "| distinct training families D | success % [95% CI] | replicate means % |", "|---|---|---|"]
        for d in have:
            md.append(f"| {d} | {ci(prim[str(d)])} | " + ", ".join(pct(v) for v in prim[str(d)]["replicate_means"]) + " |")
        md += ["", f"**D = 1,600 minus D = 25: {100 * diff['mean']:+.1f} points [{100 * diff['lo']:+.1f}, "
                   f"{100 * diff['hi']:+.1f}]. H1 is {R['primary']['H1']}** (supported: at least +10 with the interval "
                   f"above zero; refuted: interval entirely below +10)."]
        if sl:
            md.append(f"Trend: {100 * sl['mean']:+.2f} points per doubling of D [{100 * sl['lo']:+.2f}, "
                      f"{100 * sl['hi']:+.2f}] (least-squares slope on log2 D).")
        md.append("")

        # ---- every split
        md += ["### All splits (success %)", "", "| split | " + " | ".join(f"D = {d}" for d in have) +
               " | D1600 - D25 |", "|---|" + "---|" * (len(have) + 1)]
        for split in TESTS:
            ys = [cube(names(tag, d, reps), split)[0] for d in have]
            bs = boot(ys)
            mm = [float(y.mean()) for y in ys]
            cells = {str(d): interval(bs[:, i], mm[i]) for i, d in enumerate(have)}
            df = interval(bs[:, hi] - bs[:, lo], mm[hi] - mm[lo])
            R["splits"][split] = {"levels": cells, "D1600_minus_D25": df}
            md.append(f"| {split[3:]} | " + " | ".join(ci(cells[str(d)]) for d in have) +
                      f" | {100 * df['mean']:+.1f} [{100 * df['lo']:+.1f}, {100 * df['hi']:+.1f}] |")
        own, v1row, gap = {}, {}, {}
        for d in have:  # splits whose tasks differ between runs, or that have no family structure
            per = [by_split(load("e1", n)) for n in names(tag, d, reps)]
            o = [float(np.mean([r["success"] for r in p["own"]])) for p in per]
            v = [float(np.mean([r["success"] for s in V1 for r in p[s]])) for p in per]
            c = [float(np.mean([r["success"] for r in p["v2/test_comp"]])) for p in per]
            own[str(d)] = {"mean": float(np.mean(o)), "replicates": o}
            v1row[str(d)] = {"mean": float(np.mean(v)), "replicates": v,
                             "by_split": {s[3:]: float(np.mean([np.mean([r["success"] for r in p[s]]) for p in per]))
                                          for s in V1}}
            gap[str(d)] = {"mean": float(np.mean(o) - np.mean(c)), "replicates": [a - b for a, b in zip(o, c)]}
        R["own_families"], R["v1_anchor"], R["gap_own_minus_test_comp"] = own, v1row, gap
        rng = lambda v: f"{pct(v['mean'])} ({pct(min(v['replicates']))}-{pct(max(v['replicates']))})"  # noqa: E731
        md.append("| own training families, new instances (range over replicates) | " +
                  " | ".join(rng(own[str(d)]) for d in have) + f" | {100 * (own['1600']['mean'] - own['25']['mean']):+.1f} |")
        md.append("| gap: own families minus test_comp (points) | " +
                  " | ".join(f"{100 * gap[str(d)]['mean']:.1f}" for d in have) + " | |")
        md.append("| v1 anchor, 720 hand-written tasks (range over replicates) | " +
                  " | ".join(rng(v1row[str(d)]) for d in have) +
                  f" | {100 * (v1row['1600']['mean'] - v1row['25']['mean']):+.1f} |")
        md += ["", "v1 anchor reference points: " + "; ".join(f"{k} {pct(v)}%" for k, v in V1_REF.items()) + ".", ""]

        # ---- secondary: restricted to families the run's training set covers; strict success
        md += ["### Secondary endpoints on `test_comp`", "",
               "| endpoint | " + " | ".join(f"D = {d}" for d in have) + " | D1600 - D25 |", "|---|" + "---|" * (len(have) + 1)]
        R["secondary"] = {}
        for label2, key, mask in (("strict success (no unnecessary or dependency-unsafe call)", "strict_success", None),
                                  ("families whose tools all occur in the run's training set", "success", covered("tools")),
                                  ("...share of test_comp families that qualify", None, covered("tools"))):
            if key is None:
                share = [float(np.mean([[mask(n, f) for f in cube([n], "v2/test_comp")[1]] for n in names(tag, d, reps)]))
                         for d in have]
                R["secondary"]["tool_covered_share"] = dict(zip(map(str, have), share))
                md.append(f"| {label2} | " + " | ".join(pct(v) for v in share) + " | |")
                continue
            ys = [cube(names(tag, d, reps), "v2/test_comp", key, mask)[0] for d in have]
            bs = boot(ys)
            mm = [float(np.nanmean(y)) for y in ys]
            cells = {str(d): interval(bs[:, i], mm[i]) for i, d in enumerate(have)}
            df = interval(bs[:, hi] - bs[:, lo], mm[hi] - mm[lo])
            R["secondary"][label2] = {"levels": cells, "D1600_minus_D25": df}
            md.append(f"| {label2} | " + " | ".join(ci(cells[str(d)]) for d in have) +
                      f" | {100 * df['mean']:+.1f} [{100 * df['lo']:+.1f}, {100 * df['hi']:+.1f}] |")
        md.append("")

        # ---- what each level covers, and success by task property
        md += ["### What the training subsets cover (mean over replicates)", "",
               "| D | base graphs | gold tools (of 79) | practised edges (of 229) | gold calls per task | hops 1/2/3/4 % |",
               "|---|---|---|---|---|---|"]
        for d in have:
            cs = [sets[f"r{r}_D{d}"] for r in reps]
            hops = [np.mean([c["hops"].get(str(h), 0) / d for c in cs]) for h in (1, 2, 3, 4)]
            S["coverage"][f"{tag}_D{d}"] = {"tools": float(np.mean([len(c["tools"]) for c in cs])),
                                            "edges": float(np.mean([len(c["edges"]) for c in cs]))}
            md.append(f"| {d} | {np.mean([c['base_graphs'] for c in cs]):.0f} | {np.mean([len(c['tools']) for c in cs]):.0f} | "
                      f"{np.mean([len(c['edges']) for c in cs]):.0f} | {np.mean([c['mean_calls'] for c in cs]):.2f} | "
                      + " / ".join(f"{100 * h:.0f}" for h in hops) + " |")
        md += ["", "### `test_comp` success % by task property (replicates pooled)", "",
               "| property | value | tasks | " + " | ".join(f"D = {d}" for d in have) + " |",
               "|---|---|---|" + "---|" * len(have)]
        R["by_property"] = {}
        rows = {d: [r for n in names(tag, d, reps) for r in load("e1", n) if r["split"] == "v2/test_comp"] for d in have}
        for prop in ("hops", "mod", "phr"):
            for val in sorted({r[prop] for r in rows[have[0]]}, key=str):
                cells = [float(np.mean([r["success"] for r in rows[d] if r[prop] == val])) for d in have]
                n = sum(r[prop] == val for r in rows[have[0]]) // len(list(reps))
                R["by_property"][f"{prop}={val}"] = dict(zip(map(str, have), cells))
                md.append(f"| {prop} | {val} | {n} | " + " | ".join(pct(c) for c in cells) + " |")
        md.append("")

        # ---- diagnostics and variance
        md += ["### Diagnostics on `test_comp` (replicates pooled)", "", "| D | " + " | ".join(DIAG) + " |",
               "|---|" + "---|" * len(DIAG)]
        R["diagnostics"] = {}
        for d in have:
            vals = {k: float(np.nanmean([r[k] for r in rows[d]])) for k in DIAG}
            R["diagnostics"][str(d)] = vals
            md.append(f"| {d} | " + " | ".join(pct(vals[k]) if k in DIAG[:4] else f"{vals[k]:.2f}" for k in DIAG) + " |")
        vc = {str(d): variance_components(cube(names(tag, d, reps), "v2/test_comp")[0]) for d in have}
        af = arm_family_variance(cube(names(tag, 25, reps), "v2/test_comp")[0],
                                 cube(names(tag, 1600, reps), "v2/test_comp")[0])
        R["variance_components"], R["level_x_family"] = vc, af
        md += ["", "### Variance components on `test_comp` (probability scale)", "",
               "| D | within-cell variance | replicate x family sd | residual replicate sd | sd of replicate means | "
               "sd across families |", "|---|---|---|---|---|---|"]
        for d in have:
            c = vc[str(d)]
            md.append(f"| {d} | {c['within']:.3f} | {max(c['seed_family'], 0) ** 0.5:.3f} | {c['seed_sd']:.3f} | "
                      f"{c['replicate_means_sd']:.3f} | {c['family_sd']:.3f} |")
        md += ["", f"Level x family sd between D = 25 and D = 1,600 after removing replicate and task noise: "
                   f"{max(af['arm_family'], 0) ** 0.5:.3f}.", ""]
        R["seed_sd_max"] = max(c["replicate_means_sd"] for c in vc.values())
        R["gpu_seconds"] = {str(d): {k: float(np.mean([seconds(run_info('e1', n))[k] for n in names(tag, d, reps)]))
                                     for k in ("train_s", "score_s")} for d in have}
        stab = {n: stability(RUNS / "e1" / n / "train/train_log.jsonl") for d in have for n in names(tag, d, reps)}
        R["unstable_runs"] = sorted(n for n, v in stab.items() if not v["stable"])
        R["final_val_loss"] = {str(d): float(np.mean([stab[n]["final_val_loss"] for n in names(tag, d, reps)])) for d in have}
        S["students"][tag] = R

    # ---- baselines
    md += ["## Baselines without training (success %)", "", "| model | " + " | ".join(s[3:] for s in TESTS) +
           " | v1 anchor |", "|---|" + "---|" * (len(TESTS) + 1)]
    for n in ("e1_s05_base", "e1_s05_fewshot", "e1_s15_base", "e1_s15_fewshot"):
        sp = by_split(load("e1", n))
        if not sp:
            continue
        vals = {s: float(np.mean([r["success"] for r in sp[s]])) for s in TESTS if sp.get(s)}
        vals["v1"] = float(np.mean([r["success"] for s in V1 for r in sp[s]]))
        S["baselines"][n] = vals
        md.append(f"| {n[3:]} | " + " | ".join(pct(vals.get(s)) for s in TESTS) + f" | {pct(vals['v1'])} |")
    md.append("")

    # ---- decisions that follow (experiment plan)
    h05 = S["students"].get("s05", {}).get("primary", {})
    h15 = S["students"].get("s15", {}).get("primary", {})
    if h05:
        if h05["H1"] == "supported" and h05["ceiling_at_least_40"]:
            dec = "H1 supported for 0.5B and test_comp at D = 1,600 is at least 40%: Experiment 2 on the 0.5B student"
        elif h05["H1"] != "supported" and h15 and h15["H1"] == "supported":
            dec = "H1 not supported for 0.5B but supported for 1.5B: Experiment 2 on the 1.5B student"
        elif h05["H1"] == "supported" and not h05["ceiling_at_least_40"] and not (h15 and h15["ceiling_at_least_40"]):
            dec = ("H1 supported but test_comp at D = 1,600 is below 40% for both sizes: revise the held-out "
                   "definition or the student before Experiment 2")
        elif h05["H1"] == "supported":
            dec = ("H1 supported for 0.5B with test_comp at D = 1,600 below 40%, while the 1.5B student reaches 40%: "
                   "not a row of the pre-registered table; see the report")
        elif h05["H1"] == "refuted" and h15 and h15["H1"] == "refuted":
            dec = "H1 refuted for both sizes: stop the loop programme and investigate task representation"
        else:
            dec = "no row of the pre-registered decision table applies cleanly; see the report"
        sd = max(S["students"][t]["seed_sd_max"] for t in S["students"])
        S["decision"] = {"rule": dec, "seed_sd_on_test_comp": sd, "experiment_2_seeds_per_main_arm": 8 if sd > 0.03 else 5}
        md += ["## Pre-registered decision", "", f"- {dec}.",
               f"- Largest sd of replicate means on `test_comp`: {sd:.3f} "
               f"({'above' if sd > 0.03 else 'at or below'} 0.03, so Experiment 2 would use "
               f"{8 if sd > 0.03 else 5} seeds per main arm).", ""]
    (out / "summary.json").write_text(json.dumps(S, indent=1) + "\n")
    (out / "tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


