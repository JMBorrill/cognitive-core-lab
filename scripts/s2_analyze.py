def load(exp: str, name: str) -> list[dict]:
    p = RUNS / exp / name / "metrics.jsonl"
    return [json.loads(l) for l in open(p)] if p.exists() else []


def by_split(rows: list[dict]) -> dict[str, list[dict]]:
    out = defaultdict(list)
    for r in rows:
        out[r["split"]].append(r)
    return out


def pct(x) -> str:
    return "-" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.1f}"


def ci(d: dict) -> str:
    return f"{100 * d['mean']:.1f} [{100 * d['lo']:.1f}, {100 * d['hi']:.1f}]"


def stability(log_path: Path) -> dict:
    """The Study 01 rule (scripts/stability_log.py): smoothed loss never above 1.5x its step-10 value after
    step 20, and the late median gradient norm below 10x the early one."""
    L = [json.loads(x) for x in open(log_path) if x.strip()]
    loss, gn = [r["loss"] for r in L], [r["grad_norm"] for r in L]
    ma = [sum(loss[max(0, i - 4): i + 1]) / len(loss[max(0, i - 4): i + 1]) for i in range(len(loss))]
    rec = {"steps": len(L), "loss_ok": max(ma[20:]) <= 1.5 * ma[9],
           "gradnorm_ok": st.median(gn[-20:]) < 10 * st.median(gn[:10]), "ma10": ma[9], "max_ma_after20": max(ma[20:]),
           "gn_first10": st.median(gn[:10]), "gn_last20": st.median(gn[-20:]), "final_loss_ma": ma[-1],
           "final_val_loss": next((r["val_loss"] for r in reversed(L) if "val_loss" in r), None),
           "tok_per_s": L[-1]["tok_per_s"], "seq_tokens": sum(r["seq_tokens"] for r in L)}
    rec["stable"] = bool(rec["loss_ok"] and rec["gradnorm_ok"])
    return rec


def run_info(exp: str, name: str) -> dict:
    d = RUNS / exp / name
    out = {}
    for f in ("run.json", "train_run.json"):
        if (d / f).exists():
            out[f[:-5]] = json.loads((d / f).read_text())
    return out


def seconds(info: dict) -> dict:
    """GPU-seconds a run spent training and scoring (excluding job start-up)."""
    train = info.get("train_run", {}).get("summary", {}).get("train_time_s", 0.0)
    score = sum(s["seconds"] for s in info.get("run", {}).get("scoring", []))
    return {"train_s": round(train, 1), "score_s": round(score, 1)}


