def e0() -> None:
    out = OUT / "e0"
    out.mkdir(parents=True, exist_ok=True)
    ref = json.loads((ROOT / "results/summary.json").read_text())["configs"]
    prices = json.loads((ROOT / "configs/study02/budget.json").read_text())["flavors"]
    S: dict = {"reproduction": {}, "conventional": {}, "calibration": {}, "runs": {}}
    md = ["# Study 02, Experiment 0: results (generated by scripts/s2_analyze.py e0)", ""]

    def run_row(name):
        sp = by_split(load("e0", name))
        acc = {s: float(np.mean([r["success"] for r in sp[s]])) if sp.get(s) else None for s in ["v1/val_pool"] + V1}
        log = RUNS / "e0" / name / "train/train_log.jsonl"
        stab = stability(log) if log.exists() else None
        S["runs"][name] = {"success": acc, "stability": stab, **seconds(run_info("e0", name)),
                           "n": {s: len(v) for s, v in sp.items()}}
        return acc, stab

    # ---- step B: reproduction
    md += ["## Step B: reproduction of Study 01 (rank 16, alpha 320, blocks 8-23, lr 1e-5, uncorrected Adam)", "",
           "| run | eval_id | eval_ood | eval_unseen | eval_renamed | stable | final val loss |", "|---|---|---|---|---|---|---|"]
    passed = True
    for v in ("B", "C"):
        accs = []
        for seed in (0, 1, 2):
            acc, stab = run_row(f"e0_repro_{v}_s{seed}")
            accs.append(acc)
            md.append(f"| {v}_s{seed} | " + " | ".join(pct(acc[s]) for s in V1) +
                      f" | {'yes' if stab and stab['stable'] else 'NO'} | {stab['final_val_loss']:.4f} |")
            passed &= bool(stab and stab["stable"])
        mean = {s: float(np.mean([a[s] for a in accs])) for s in V1}
        want = {s: ref[v][s[3:]]["success"]["mean"] for s in V1}
        ok = {s: abs(mean[s] - want[s]) <= 0.05 for s in ("v1/eval_id", "v1/eval_ood")}
        passed &= all(ok.values())
        S["reproduction"][v] = {"mean": mean, "study01": want, "diff": {s: mean[s] - want[s] for s in V1},
                                "within_5_points": ok}
        md.append(f"| **{v} mean** | " + " | ".join(f"**{pct(mean[s])}**" for s in V1) + " | | |")
        md.append(f"| {v} in Study 01 (MLX) | " + " | ".join(pct(want[s]) for s in V1) + " | | |")
        md.append(f"| {v} difference | " + " | ".join(f"{100 * (mean[s] - want[s]):+.1f}" for s in V1) + " | | |")
    S["reproduction"]["pass"] = bool(passed)
    md += ["", f"Pass criterion (means of `eval_id` and `eval_ood` within 5 points of Study 01 for B and C, every run "
               f"stable): **{'met' if passed else 'NOT met'}**.", ""]

    # ---- step C: conventional settings
    md += ["## Step C: conventional settings on variant C (all 24 blocks, alpha 32, bias-corrected AdamW, seed 0)", "",
           "| lr | steps | val_pool | eval_id | eval_ood | eval_unseen | eval_renamed | stable | final val loss |",
           "|---|---|---|---|---|---|---|---|---|"]
    grid = {}
    for lr in ("5e-05", "0.0001", "0.0002"):
        for steps in (250, 500):
            name = f"e0_conv_C_lr{lr}_st{steps}"
            acc, stab = run_row(name)
            grid[(lr, steps)] = {"name": name, "val_pool": acc["v1/val_pool"], "stable": bool(stab and stab["stable"]),
                                 "eval_ood": acc["v1/eval_ood"]}
            md.append(f"| {lr} | {steps} | {pct(acc['v1/val_pool'])} | " + " | ".join(pct(acc[s]) for s in V1) +
                      f" | {'yes' if stab and stab['stable'] else 'NO'} | {stab['final_val_loss']:.4f} |")
    default = grid[("0.0001", 250)]
    best_key = max(grid, key=lambda k: (grid[k]["val_pool"], grid[k]["stable"]))
    best = grid[best_key]
    replace = (not default["stable"]) or (best["val_pool"] - default["val_pool"] > 0.03)
    chosen = best if replace else default
    best_ood = max(g["eval_ood"] for g in grid.values())
    S["conventional"] = {"grid": {f"lr{k[0]}_st{k[1]}": v for k, v in grid.items()}, "default": default["name"],
                         "best_val_pool": best["name"], "default_replaced": bool(replace), "chosen": chosen["name"],
                         "best_eval_ood": best_ood, "gap_was_artifact": bool(best_ood >= 0.60)}
    md += ["", f"Rule: keep lr 1e-4 with two passes (250 steps) unless it is unstable or more than 3 points below the "
               f"best `val_pool` setting. Default: {pct(default['val_pool'])} (stable: {default['stable']}); best: "
               f"`{best['name']}` at {pct(best['val_pool'])}. **Chosen: `{chosen['name']}`.**",
           f"Best `eval_ood` in the grid: {pct(best_ood)} (reported, not used for selection). "
           f"The 60% threshold for calling the Study 01 gap a training artefact is "
           f"**{'reached' if best_ood >= 0.60 else 'not reached'}**.", ""]

    # ---- step D: repeatability
    a = {(r["split"], r["task_id"]): r["success"] for r in load("e0", "e0_repro_B_s0")}
    b = {(r["split"], r["task_id"]): r["success"] for r in load("e0", "e0_repeat_B_s0")}
    common = sorted(set(a) & set(b))
    flips = sum(a[k] != b[k] for k in common)
    S["repeatability"] = {"episodes": len(common), "flips": flips, "flip_rate": flips / max(1, len(common))}
    md += ["## Step D: repeatability", "",
           f"`e0_repro_B_s0` scored twice in separate jobs: {flips} of {len(common)} episodes differ in success "
           f"({100 * flips / max(1, len(common)):.2f}%). Threshold for action: 2%.", ""]

    # ---- step A: throughput
    md += ["## Step A: throughput", "",
           "| flavour | USD/h | GPU | training tokens/s | USD per million training tokens | eval_id episodes/s |",
           "|---|---|---|---|---|---|"]
    for fl in ("l4x1", "a10g-small"):
        name = f"e0_calib_{fl}"
        log = RUNS / "e0" / name / "train/train_log.jsonl"
        if not log.exists():
            continue
        stab, info = stability_short(log), run_info("e0", name)
        ev = next((s for s in info.get("run", {}).get("scoring", []) if s["split"] == "v1/eval_id"), None)
        eps = ev["run_now"] / ev["seconds"] if ev and ev["seconds"] else None
        usd = prices[fl] / (stab["tok_per_s"] * 3600) * 1e6
        S["calibration"][fl] = {"tok_per_s": stab["tok_per_s"], "usd_per_million_tokens": usd, "eval_eps_per_s": eps,
                                "gpu": info.get("run", {}).get("gpu")}
        md.append(f"| {fl} | {prices[fl]:.2f} | {info.get('run', {}).get('gpu')} | {stab['tok_per_s']:.0f} | {usd:.4f} | "
                  f"{eps:.2f} |")
    if S["calibration"]:
        cheapest = min(S["calibration"], key=lambda f: S["calibration"][f]["usd_per_million_tokens"])
        S["calibration"]["chosen"] = cheapest
        md += ["", f"Cheaper per training token: **{cheapest}**.", ""]

    train_cfg = json.loads((ROOT / "configs/study02/e0" / f"{chosen['name']}.json").read_text())["train"]
    decision = {"bridge_passed": bool(passed), "train": train_cfg, "chosen_run": chosen["name"],
                "flavor": S["calibration"].get("chosen"), "flip_rate": S["repeatability"]["flip_rate"],
                "best_eval_ood_conventional": best_ood,
                "proceed_to_experiment_1": bool(passed and S["repeatability"]["flip_rate"] <= 0.02)}
    S["decision"] = decision
    (out / "decision.json").write_text(json.dumps(decision, indent=1) + "\n")
    (out / "summary.json").write_text(json.dumps(S, indent=1) + "\n")
    (out / "tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    print(json.dumps({k: v for k, v in decision.items() if k != "train"}, indent=1))


def stability_short(log_path: Path) -> dict:
    L = [json.loads(x) for x in open(log_path) if x.strip()]
    return {"tok_per_s": L[-1]["tok_per_s"], "steps": len(L)}


