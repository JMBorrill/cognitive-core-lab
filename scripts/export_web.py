"""Export published artifacts for the showcase (web/public/data). Only real run outputs are exported.

    python scripts/export_web.py
"""

from __future__ import annotations

import gzip
import json
import re
import shutil
import subprocess
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ccl.data import load_tasks  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "web" / "public" / "data"
RUNS = ROOT / "results" / "runs"
SPLITS = ["eval_id", "eval_ood", "eval_unseen", "eval_renamed"]
# Seed-0 run used for replayed traces of each configuration.
REPLAY = {"A": "A_base", "A_fewshot": "A_fewshot", "B": "B_s0", "C": "C_s0", "D": "Dmix_s0", "Dseq": "Dseq_s0",
          "teacher": "teacher", "oracle": "oracle"}
DESCRIPTIONS = {
    "A": "Unmodified Qwen2.5-0.5B-Instruct with the shared system prompt.",
    "A_fewshot": "Same weights as A; the system prompt adds two worked examples (prompting, no weight change).",
    "B": "LoRA on execution-verified demonstrations generated by the Qwen3.5-4B teacher.",
    "C": "LoRA on trajectories from an independent programmatic oracle, executed and validated.",
    "D": "LoRA on the union of B and C data, shuffled together (same step budget).",
    "Dseq": "LoRA trained on B data for half the steps, then C data for the other half.",
    "teacher": "Qwen3.5-4B (MLX 4-bit) — reference only; it produced the B data.",
    "oracle": "Programmatic policy reading the gold task graph — the validator's ceiling, not a model.",
}


def failure_mode(m: dict) -> str | None:
    if m["success"]:
        return None
    if m["parse_errors"]:
        return "malformed_output"
    if m["hallucinated_tools"]:
        return "hallucinated_tool"
    if not m["check_no_permission_violation"]:
        return "permission_violation"
    if not m["check_no_retry_after_denial"]:
        return "retried_after_denial"
    if not m["dependency_safe"]:
        return "dependency_violation"
    if not m["check_required_calls"]:
        return "missing_or_wrong_call"
    if not m["check_effects"]:
        return "wrong_side_effect"
    if not m["check_status"]:
        return "wrong_final_status"
    if not m["check_facts"]:
        return "wrong_answer"
    return "other"


def slim_trace(t: dict) -> dict:
    return {"turns": [{k: x[k] for k in ("turn", "raw", "kind", "strict", "error", "gen_tokens")} for x in t["turns"]],
            "calls": [{k: c[k] for k in ("turn", "tool", "outcome", "args", "result", "approval")} for c in t["calls"]],
            "final": t["final"], "status": t["status"], "termination": t["termination"]}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    configs = json.loads((ROOT / "configs" / "models.json").read_text())
    available = {k: (RUNS / v / "metrics.jsonl").exists() for k, v in REPLAY.items()}

    tasks = {s: {t.task_id: (i, t) for i, t in enumerate(load_tasks(ROOT / "data/v1/tasks" / f"{s}.jsonl"))}
             for s in SPLITS}

    # Load per-config metrics + traces (seed-0 replay run).
    metrics, traces = {}, {}
    for key, run in REPLAY.items():
        if not available[key]:
            continue
        metrics[key] = {(r["split"], r["task_id"]): r for r in map(json.loads, open(RUNS / run / "metrics.jsonl"))
                        if r["split"] in SPLITS}
        traces[key] = {}
        with gzip.open(RUNS / run / "traces.jsonl.gz", "rt") as f:
            for line in f:
                r = json.loads(line)
                if r["split"] in SPLITS:
                    traces[key][(r["split"], r["task_id"])] = r["trace"]

    # Showcase: a fixed, family-stratified sample of tasks shared across all configs.
    pick = []
    for split in SPLITS:
        seen = defaultdict(int)
        for tid, (i, t) in tasks[split].items():
            if seen[t.family] < 2:
                seen[t.family] += 1
                pick.append((split, tid))
    show_tasks = []
    for split, tid in pick:
        i, t = tasks[split][tid]
        show_tasks.append({"key": f"{split}:{i}", "split": split, "index": i, "task_id": tid, "family": t.family,
                           "template": t.template, "role": t.role, "request": t.request, "depth": t.depth,
                           "today": t.today, "catalog": [s.signature() for s in t.catalog],
                           "expected_status": t.expected_status, "answer_facts": t.answer_facts,
                           "graph_seen": "graph_seen" in t.tags,
                           "gold": [{"id": g.id, "tool": g.tool, "deps": g.deps, "optional": g.optional,
                                     "execute": g.execute} for g in t.gold]})
    show_traces = {}
    for key in traces:
        show_traces[key] = {}
        for st in show_tasks:
            k = (st["split"], st["task_id"])
            if k in traces[key]:
                m = metrics[key][k]
                show_traces[key][st["key"]] = {**slim_trace(traces[key][k]), "success": bool(m["success"]),
                                               "checks": {c[6:]: bool(v) for c, v in m.items() if c.startswith("check_")},
                                               "failure_mode": failure_mode(m), "source_run": REPLAY[key]}

    # Failure gallery: up to 3 examples per (config, failure mode).
    failures = {}
    for key in metrics:
        groups = defaultdict(list)
        for k, m in metrics[key].items():
            fm = failure_mode(m)
            if fm and len(groups[fm]) < 3:
                i, t = tasks[k[0]][k[1]]
                groups[fm].append({"split": k[0], "index": i, "task_id": k[1], "family": t.family,
                                   "request": t.request, "role": t.role, "expected_status": t.expected_status,
                                   "trace": slim_trace(traces[key][k])})
        counts = defaultdict(int)
        for m in metrics[key].values():
            fm = failure_mode(m)
            if fm:
                counts[fm] += 1
        failures[key] = {"counts": dict(counts), "total": len(metrics[key]), "examples": dict(groups)}

    # Training curves and dataset manifests.
    training = {}
    for d in sorted((ROOT / "runs").glob("*")):
        if (d / "train_log.jsonl").exists() and re.fullmatch(r".+_s\d+", d.name):
            log = [json.loads(l) for l in open(d / "train_log.jsonl")]
            training[d.name] = {"log": [{k: r.get(k) for k in ("step", "loss", "val_loss", "tok_per_s", "peak_mem_gb")}
                                        for r in log],
                                "summary": json.loads((d / "summary.json").read_text()) if (d / "summary.json").exists() else None}

    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "git_commit": commit or None,
        "configs": {k: {"label": configs[k]["label"], "description": DESCRIPTIONS[k], "has_results": available[k],
                        "replay_run": REPLAY[k]} for k in REPLAY},
        "splits": {"eval_id": "held-out instances of training templates",
                   "eval_ood": "templates never seen in training (novel phrasing / task graphs / depth 4-5)",
                   "eval_unseen": "tool domains never seen in training (inventory, maps)",
                   "eval_renamed": "training templates with every tool/parameter renamed (held-out alias vocabulary)"},
    }
    for name, obj in [("manifest", manifest), ("showcase", {"tasks": show_tasks, "traces": show_traces}),
                      ("failures", failures), ("training", training)]:
        (OUT / f"{name}.json").write_text(json.dumps(obj, ensure_ascii=False))
    for src, dst in [("results/summary.json", "results.json"), ("data/v1/teacher/manifest.json", "teacher.json"),
                     ("data/v1/manifest.json", "datasets.json"), ("data/v1/leakage_audit.json", "leakage.json"),
                     ("docs/REPORT.md", "report.md")]:
        if (ROOT / src).exists():
            shutil.copy(ROOT / src, OUT / dst)
    print("exported:", sorted(p.name for p in OUT.iterdir()), "configs with results:",
          [k for k, v in available.items() if v])


if __name__ == "__main__":
    main()
